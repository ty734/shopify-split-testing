// Keep the storefront anti-flicker gate in sync with what the running tests
// actually touch.
//
// WHY THIS EXISTS AT ALL
// The gate has to run SYNCHRONOUSLY in <head>, before anything paints, which
// means the browser must already know which selectors to hide when the HTML is
// served. lw-split.js cannot supply that — it does not finish loading until
// ~640ms, long after first paint. So the list has to be baked into the theme.
//
// WHY NOT A SHOPIFY METAFIELD
// That was the first design, but it needs an Admin API token with write scope
// and the only token on hand is `read_orders`. Minting a write-scoped token
// through the Dev Dashboard is real setup for a list that changes a few times a
// month. The Shopify CLI can already write theme files, so
// this generates the snippet and pushes it — no new credential.
//
//   npm run gate:sync           # check + push if the list changed
//   npm run gate:sync -- --dry  # print what would change, push nothing
//
// Safe to run on a schedule: it is a no-op when nothing changed.
import dotenv from "dotenv";
dotenv.config({ path: ".env.local" });
import { execFileSync } from "child_process";
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "fs";
import { join } from "path";

// Set these in .env.local. Always look up the LIVE theme id; never hardcode it.
const STORE = process.env.SHOP_DOMAIN || "";            // your-store.myshopify.com
const THEME = process.env.SHOPIFY_THEME_ID || "";       // live theme id
const CONFIG_URL = (process.env.SPLIT_APP_URL || "") + "/api/split/config";
if (!STORE || !THEME || !process.env.SPLIT_APP_URL) {
  console.error("Set SHOP_DOMAIN, SHOPIFY_THEME_ID and SPLIT_APP_URL in .env.local");
  process.exit(1);
}
const WORKDIR = join(process.cwd(), ".theme-gate");
const SNIPPET = "snippets/lwsplit-gate.liquid";

function render(selectors: string[]): string {
  const list = JSON.stringify(selectors);
  return `{%- comment -%}
  GENERATED by lw-split \`npm run gate:sync\` — do not hand-edit, it will be
  overwritten. Regenerate after starting/stopping any test.

  Anti-flicker gate. Hides ONLY the elements a currently-running test rewrites,
  then reveals them once lw-split.js has applied its changes (or after a safety
  timeout, so a script failure can never leave the page blank).

  Without this, the variant arm of a price test renders the CONTROL price and
  then visibly flips to the test price — bad on its own, and an asymmetric
  handicap on the variant, since the control arm never flickers.

  Only 'replace' / 'remove' / price changes contribute selectors. An 'insert'
  test has nothing pre-existing to hide, so hiding its anchor would blank real
  content for no reason.

  Selectors below are compiled from the live config at generation time.
{%- endcomment -%}
<script>
(function(){
  var H = ${list};
  window.__LWSPLIT_HIDE__ = H;
  if (!H.length) { window.__LWSPLIT_REVEAL__ = function(){}; return; }
  var s = document.createElement('style');
  s.id = '__lwsplit_gate__';
  s.textContent = H.join(',') + '{visibility:hidden !important;}';
  document.documentElement.appendChild(s);
  var done = false;
  function reveal(){
    if (done) return; done = true;
    var el = document.getElementById('__lwsplit_gate__');
    if (el && el.parentNode) el.parentNode.removeChild(el);
  }
  window.__LWSPLIT_REVEAL__ = reveal;
  // Safety net: never hold content hostage to a script that failed to load.
  setTimeout(reveal, 2500);
})();
</script>
`;
}

(async () => {
  const dry = process.argv.includes("--dry");
  const res = await fetch(CONFIG_URL, { headers: { accept: "application/json" } });
  if (!res.ok) throw new Error(`config HTTP ${res.status}`);
  const cfg = (await res.json()) as { selectors?: string[] };
  const selectors = [...new Set(cfg.selectors || [])].sort();
  console.log(`live hide list (${selectors.length}):`, selectors.length ? selectors.join(", ") : "(none)");

  if (!existsSync(WORKDIR)) mkdirSync(WORKDIR, { recursive: true });
  // On Windows the global npm install is a .cmd shim, which execFileSync cannot
  // resolve by bare name — it throws ENOENT. shell:true lets the platform find it.
  const BIN = process.platform === "win32" ? "shopify.cmd" : "shopify";
  const sh = (args: string[]) =>
    execFileSync(BIN, args, {
      cwd: WORKDIR,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
      shell: process.platform === "win32",
    });

  // Pull only our snippet so nothing else in the theme can be touched.
  try {
    sh(["theme", "pull", "--store", STORE, "--theme", THEME, "--only", SNIPPET, "--path", "."]);
  } catch {
    console.log("  (snippet not on the theme yet — will be created)");
  }

  const path = join(WORKDIR, SNIPPET);
  const next = render(selectors);
  const current = existsSync(path) ? readFileSync(path, "utf8") : "";
  if (current.trim() === next.trim()) {
    console.log("no change — theme already matches.");
    return;
  }
  console.log(dry ? "WOULD update the snippet:" : "updating the snippet:");
  console.log(next.split("\n").filter((l) => l.includes("var H =")).join("\n").trim());
  if (dry) return;

  mkdirSync(join(WORKDIR, "snippets"), { recursive: true });
  writeFileSync(path, next, "utf8");
  sh(["theme", "push", "--store", STORE, "--theme", THEME, "--only", SNIPPET, "--path", ".", "--allow-live", "--force"]);
  console.log("pushed.");
})().catch((e) => {
  console.error("GATE SYNC FAILED:", e.message || e);
  process.exit(1);
});
